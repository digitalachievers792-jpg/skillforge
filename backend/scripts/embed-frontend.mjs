import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const backend = fileURLToPath(new URL('..', import.meta.url));
const repo = fileURLToPath(new URL('../..', import.meta.url));
const frontend = `${repo}frontend`;
const dist = `${frontend}/dist`;
const outFile = `${backend}src/frontend-bundle.js`;

console.log('[embed-frontend] building frontend...');
execSync('npm ci', { cwd: frontend, stdio: 'inherit' });
execSync('npm run build', { cwd: frontend, stdio: 'inherit' });

if (!existsSync(dist)) throw new Error('frontend/dist missing after build');

function walk(dir, base, acc) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    const rel = path.posix.join(base, entry);
    if (statSync(full).isDirectory()) walk(full, rel, acc);
    else acc.push('/' + rel);
  }
  return acc;
}

const files = walk(dist, '', []);
const bundle = {};
for (const file of files) {
  bundle[file] = readFileSync(path.join(dist, file.replace(/^\//, ''))).toString('base64');
}

const js = `// GENERATED by scripts/embed-frontend.mjs - do not edit manually
// Embeds the built frontend as base64 strings so the serverless function can
// serve it without depending on static files or bundler transforms.
module.exports = ${JSON.stringify(bundle)};
`;

writeFileSync(outFile, js);
console.log(`[embed-frontend] done -> src/frontend-bundle.js (${files.length} files, ${Math.round(Buffer.byteLength(js) / 1024)} KB)`);
